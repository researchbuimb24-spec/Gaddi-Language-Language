def get_hindi_gloss(english_gloss):
    eg = english_gloss.strip().lower()
    # 1. Exact lookup
    if eg in GLOSS_TO_HINDI:
        return GLOSS_TO_HINDI[eg]
    
    # 2. Try normalized "to verb"
    eg_clean = eg.replace("to ", "").strip()
    if eg_clean in GLOSS_TO_HINDI:
        return GLOSS_TO_HINDI[eg_clean]
        
    # 3. Whole-word boundary search
    import re
    # Sort keys by length descending to match longest specific phrase first
    sorted_keys = sorted(GLOSS_TO_HINDI.keys(), key=len, reverse=True)
    for k in sorted_keys:
        if re.search(r'\b' + re.escape(k) + r'\b', eg):
            return GLOSS_TO_HINDI[k]
            
    return eg

